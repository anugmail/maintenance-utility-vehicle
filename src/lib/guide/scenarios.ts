  c.sheet != null ? (Array.isArray(c.sheet) ? c.sheet : [c.sheet]) : SHEET_PAGE[c.id] != null ? [SHEET_PAGE[c.id]] : [];
export const sheetPagesOf = (g: GuideScenario) => g.cases.flatMap(casePages);

